#: Пошук згадок файлів ВИНЕСЕНО в :mod:`path_scan`.
#:
#: Стара регулярка ``((?:[\w.\-]+[\\/])*[\w.\-]+\.(?:py|js|…))`` на довгому
#: тексті без шляху працювала квадратично (50 000 символів — 32 с, тобто
#: зависання інтерфейсу). Деталі й заміри — у докстрінгу ``path_scan``.
_PATH_RE = None            # залишено як нагадування; НЕ використовується

_QUOTED = re.compile(r"[«\"'`]([^»\"'`]{2,})[»\"'`]")

#: Назва ТЕКИ у фразі: «у теці blackchpok_ide», «в папці src», «в каталозі lib».
#:
#: Навіщо окремо. Пошук шляхів бачить лише імена з розширенням, тому «скільки
#: файлів .py у теці blackchpok_ide» давало підказку ``list_dir`` БЕЗ ``path``
#: — і агент перелічував КОРІНЬ проєкту замість названої теки. Живий прогін:
#: користувач спитав про теку ``blackchpok_ide``, а відповідь була
#: «. — 38 записів» про корінь, де насправді 127 записів у теці.
#:
#: Беремо лише те, що стоїть ПІСЛЯ слова «тека/папка/каталог/dir», щоб не
#: вихопити довільне слово з фрази.
#:
#: УВАГА на ЧЕРГУВАННЯ приголосних: в українській основі «к» переходить у
#: «ц» у місцевому відмінку — «тека» → «у теці», «папка» → «у папці».
#: Перша версія писала ``тец[а-яіїєґ]*`` і ``папк…``, тому «у папці tests»
#: НЕ розпізнавалось узагалі (перевірено: ``_folder_in`` повертала ``""``).
#:
#: Друга пастка: «каталог» → «у каталозі» — там з'являється «і» ПЕРЕД
#: закінченням, тому ``каталог[а-яіїєґ]*`` теж не збігався (зловлено тестом).
#: Тому основа береться до останнього приголосного, а далі — будь-які
#: літери: ``каталог[а-яіїєґ]`` покриває «каталог», «каталогу», «каталозі».
_FOLDER_RE = re.compile(
    r"(?:те(?:к|ц)[а-яіїєґ]*|пап(?:к|ц)[а-яіїєґ]*|каталог[а-яіїєґ]*"
    r"|директор[а-яіїєґ]*|folder|directory|dir)\s+"
    r"[«\"'`]?([\w][\w.\-/\\]*)[»\"'`]?",
    re.IGNORECASE,
)

#: Те саме, але з «і»/«о» вставними в основі: «каталозі», «директорії».
_FOLDER_RE_OBLIQUE = re.compile(
    r"(?:каталоз[а-яіїєґ]*|директорі[а-яіїєґ]*|теч[а-яіїєґ]*)\s+"
    r"[«\"'`]?([\w][\w.\-/\\]*)[»\"'`]?",
    re.IGNORECASE,
)


def _folder_in(text: str) -> str:
    """Тека, названа у фразі («у теці src» → ``src``). Порожньо — не названо."""
    match = _FOLDER_RE.search(text or "") or _FOLDER_RE_OBLIQUE.search(text or "")
    if not match:
        return ""
    name = match.group(1).strip("`\"'»«").replace("\\", "/").rstrip("/")
    # Кінець речення липне до імені: «…у теці blackchpok_ide.» дало
    # ``blackchpok_ide.`` і ``list_dir`` відповів «Не папка». Прибираємо
    # кінцеві крапки/коми, але НЕ крапки всередині (``pkg.sub``).
    name = name.rstrip(".,;:!?")
    # Прийменники й слова-заглушки: «у теці проєкту», «в папці з кодом».
    if name.lower() in ("проєкту", "проекту", "проект", "проєкт", "код",
                        "коду", "ця", "цей", "the"):
        return ""
    return name


def _path_in(text: str) -> str:
    """Перший згаданий файл. Пошук лінійний — див. :mod:`path_scan`."""
    return path_scan.first_path(text or "")


def _quoted(text: str) -> str:
    match = _QUOTED.search(text or "")
    return match.group(1).strip() if match else ""


def _paths_in(text: str) -> list[str]:
    """Усі згадані файли у фразі, без повторів, у порядку згадки.

    Потрібно для фраз із кількома файлами: «додай у calc.py множення, а в
    notes.txt запиши». Раніше роутер бачив лише перший, і агент виконував
    половину прохання.

    Пошук лінійний (:mod:`path_scan`): стара регулярка на довгому тексті
    без шляху працювала квадратично й підвішувала інтерфейс.
    """
    return path_scan.find_paths(text or "")


def _has(low: str, *needles: str) -> bool:
    return any(needle in low for needle in needles)


def _word(text: str, stem: str) -> bool:
    """Чи є ``stem`` ОКРЕМИМ словом (з українськими закінченнями).

    Навіщо не ``in``: «скіл» є початком слова «скільки», тому
    «Скільки Python-файлів?» маршрутизувалось у ``read_skill`` — агент
    читав інструкцію скіла замість того, щоб порахувати файли.

    Перевіряємо і межу ПЕРЕД основою, і межу ПІСЛЯ неї. Закінчення
    перелічені явно: «скіл», «скіла», «скіли», «скілів» — це та сама дія,
    а «скільки» (де після «скіл» стоїть «ь») — ні.
    """
    return bool(re.search(
        rf"(?<![\w\u0400-\u04FF]){re.escape(stem)}"
        rf"(?:а|и|у|ів|ом|ами|ах|ям|ями|ях)?(?![\w\u0400-\u04FF])",
        text))


def _ide_rules(phrase: str) -> list[ToolHint]:
    """Правила, які стосуються саме IDE (скіли, черга, вкладки)."""
    low = (phrase or "").lower().strip()
    if not low:
        return []
    hints: list[ToolHint] = []
    path = _path_in(phrase)

    if _has(low, "які є скіли", "які скіли", "список скілів", "перелік скілів",
            "покажи скіли"):
        hints.append(ToolHint("list_skills", {}, HIGH, "запит про скіли"))
    elif _word(low, "скіл"):
        name = _quoted(phrase)
        if not name:
            match = re.search(r"скіл[а-яіїєґ]*\s+([\w\-]+)", low)
            name = match.group(1) if match else ""
        hints.append(ToolHint("read_skill", {"name": name} if name else {},
                              HIGH if name else MEDIUM, "згадано скіл"))

    # ── Підрахунок файлів ─────────────────────────────────────────────────
    # «Скільки .py файлів?» — це запит про реальний стан теки, і
    # правильний інструмент тут ``list_dir`` (або ``find_files`` для
    # підтек). Без цього правила роутер не давав жодної підказки, і
    # модель відповідала вигадкою.
    if _has(low, "скільки файл", "скільки .py", "скільки py", "скільки python",
            "скільки тест", "кількість файл", "скільки модул"):
        # Тека у фразі має пріоритет над шляхом до файлу: «скільки файлів
        # у теці src» — це питання про ТЕКУ. Раніше ``_path_in`` не бачив
        # голих імен тек, ``target`` лишався порожнім, і ``list_dir``
        # перелічував корінь.
        target = _folder_in(phrase) or path or ""
