def _hours(phrase: str) -> int:
    """Скільки годин працювати вночі (типово 6)."""
    match = re.search(r"(\d+)\s*(?:год|годин|hour)", phrase or "", re.I)
    if not match:
        return 6
    return max(1, min(int(match.group(1)), 8))


