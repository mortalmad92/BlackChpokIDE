    lines = ["Доступні дії IDE:"]
    for name, when, example in TOOL_CATALOG:
        lines.append(f"- {name} — {when} (напр. «{example}»)")
    if include_mcp:
        lines.append("")
        lines.append("Додаткові дії MCP-сервера (через master_agent_router):")
        for name, when, example in MCP_CATALOG:
            lines.append(f"- {name} — {when} (напр. «{example}»)")
    return "\n".join(lines)


