def split_into_stages(text: str, *, limit: int = MAX_STAGES) -> list[Stage]:
    """Розбити велику задачу на етапи БЕЗ моделі.

    Працює за трьома ознаками, у порядку надійності:

    1. **готовий список** — користувач сам написав «1) … 2) …» або маркери;
    2. **речення з дієсловом-наказом** — кожне речення, що починається з
       дії, стає етапом;
    3. **пункти через кому/«та»** — коли все в одному реченні.

    Якщо нічого не вдалось, повертаємо один етап з усією задачею: краще
    показати один пункт, ніж вигадати структуру, якої немає.
    """
    clean = (text or "").strip()
    if not clean:
        return []
    # Наміри всієї задачі: етап без власної дії їх успадковує.
    whole = [intent for intent in understand(clean).intents if intent != TALK]

    def make(items: list[str]) -> list[Stage]:
        return [stage_from_text(item, index, fallback_intents=whole)
                for index, item in enumerate(items[:limit]) if _clean_step(item)]

    # 1. Готовий список від користувача.
    listed: list[str] = []
    for line in clean.splitlines():
        stripped = line.strip()
        if re.match(r"^\d+[.)]\s+\S", stripped):
            listed.append(re.sub(r"^\d+[.)]\s+", "", stripped))
        elif re.match(r"^[-*•·]\s+\S", stripped):
            listed.append(stripped[2:])
    if len(listed) >= 2:
        return make(listed)

    # 2. Речення з дієсловом-наказом.
    sentences: list[str] = []
    for chunk in re.split(r"(?<=[.!?])\s+|\n+", clean):
        piece = chunk.strip()
        if not piece:
            continue
        # Склеюємо короткі хвости («… і все.») з попереднім реченням.
        if sentences and len(piece) < 18:
            sentences[-1] = f"{sentences[-1]} {piece}".strip()
        else:
            sentences.append(piece)
    action_sentences = [s for s in sentences if _starts_with_action(s)]
    if len(action_sentences) >= 2:
        return make(action_sentences)

    # 3. Пункти всередині одного речення.
    parts = _clause_parts(clean)
    if len(parts) >= 2:
        stages = make(parts)
        if stages:
            return stages

    # 4. Різні ФАЙЛИ в одному реченні — окремі етапи.
    # «додай у calc.py функцію множення, а в notes.txt запиши що зроблено»:
    # тут дві дії над двома файлами. Без цього правила агент брав перший
    # файл, робив його й зупинявся — друга половина прохання губилась.
    by_file = _split_by_files(clean, limit=limit)
    if len(by_file) >= 2:
        return make(by_file)

    return make([clean])


def _split_by_files(text: str, *, limit: int = MAX_STAGES) -> list[str]:
    """Розрізати фразу на шматки, що відповідають різним файлам.

    Кожен шматок — від згадки одного файлу до наступної згадки іншого.
    Порядок зберігаємо як у фразі, тож етапи йдуть природно.

    Хвіст на кшталт «, а в» перед наступним файлом відрізаємо: інакше
    етап читався б як «calc.py функцію множення, а в».
    """
    matches = list(path_scan.find_path_matches(text))
    if len(matches) < 2:
        return []
    pieces: list[str] = []
    for index, (start, _end, _name) in enumerate(matches):
        end = matches[index + 1][0] if index + 1 < len(matches) else len(text)
        piece = text[start:end]
        # Прибираємо сполучники й пунктуацію, що лишились на стику шматків.
        piece = re.sub(r"[,\s;—\-]*(?:а|й|та|і|потім|далі)\s+(?:в|у|на)?\s*$",
                       "", piece.strip(), flags=re.IGNORECASE)
        piece = piece.strip(" ,;.—-\n")
        if piece:
            pieces.append(piece)
    return pieces[:limit]


def _starts_with_action(sentence: str) -> bool:
    low = sentence.lower().lstrip(" -—…")
    # Дозволяємо короткий вступ («потрібно», «треба», «будь ласка»).
    low = re.sub(r"^(потрібно|треба|будь ласка|прошу|також|і|й|та|потім|далі)\s+",
                 "", low)
    return any(low.startswith(verb) for verb in _CLAUSE_VERBS)


def _clause_parts(text: str) -> list[str]:
    """Розрізати одне речення на пункти за «, а також», « і щоб», «;»."""
    # Спершу — явні розділювачі.
    pieces = re.split(r"[;]\s*|\s+а\s+також\s+|\s+також\s+|\s+потім\s+|\s+далі\s+",
                      text)
    result: list[str] = []
    for piece in pieces:
        # Усередині шматка шукаємо дієслова-накази й ріжемо перед ними.
        matches = list(re.finditer(r"\b(" + "|".join(_CLAUSE_VERBS) + r")", piece,
                                   re.I))
        if len(matches) <= 1:
            if piece.strip():
                result.append(piece.strip())
            continue
        starts = [m.start() for m in matches]
        for number, start in enumerate(starts):
            end = starts[number + 1] if number + 1 < len(starts) else len(piece)
            chunk = piece[start:end].strip(" ,.—-")
            if len(chunk) > 3:
                result.append(chunk)
    return result


