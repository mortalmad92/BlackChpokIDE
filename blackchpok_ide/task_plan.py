def _has_artifact(low: str) -> bool:
    """Чи згадано щось програмне (сайт, гра, кнопка, файл, тест…)."""
    return any(stem in low for stem in ARTIFACT_STEMS)


def _has_desire(low: str) -> bool:
    """Чи фраза висловлює бажання/прохання, а не розповідь про світ."""
    return any(stem in low for stem in DESIRE_STEMS)


def _has_complaint(low: str) -> bool:
    """Чи це скарга на несправність."""
    return any(stem in low for stem in COMPLAINT_STEMS)


def _is_code_question(low: str) -> bool:
    """Чи питання стосується коду/проєкту (а не світу взагалі)."""
    return any(stem in low for stem in CODE_QUESTION_STEMS)


def _stem_in(low: str, stems: Iterable[str]) -> bool:
    """Чи є в тексті хоч одна основа (як підрядок)."""
    return any(stem in low for stem in stems)


def _demands(low: str) -> int:
    """Скільки різних вимог у тексті (не кількість згадок, а різновидів)."""
    return sum(1 for stem in DEMAND_STEMS if stem in low)


#: Запитання, а не наказ: «як зробити чай?», «чи можна створити?».
#: Для таких фраз не виконуємо дію — людина питає, а не доручає.
_QUESTION_RE = re.compile(
    r"^\s*(як|чому|навіщо|чи|коли|де|хто|скільки)\b|"
    r"\b(як зробити|як створити|як змінити|як запустити|можна створити)\b",
    re.IGNORECASE,
)


def _is_question(low: str) -> bool:
    """Чи фраза питальна (тоді це розмова, а не доручення)."""
    return bool(_QUESTION_RE.search(low))


@dataclass
class Understanding:
    """Що зрозуміло з фрази користувача."""

    text: str = ""
    intents: list[str] = field(default_factory=list)
    #: Згадані шляхи до файлів, теки, символи в лапках.
    paths: list[str] = field(default_factory=list)
    quoted: list[str] = field(default_factory=list)
    demands: int = 0
    sentences: int = 0
    #: Чим більше — тим більша задача.
    weight: int = 0

    @property
    def primary(self) -> str:
        """Головний намір (найважливіший із знайдених)."""
        return self.intents[0] if self.intents else TALK

    @property
    def is_action(self) -> bool:
        return bool(self.intents) and self.primary != TALK

    @property
    def is_big(self) -> bool:
        """Чи варто розбивати на етапи."""
        if self.weight >= 4:
            return True
        # Кілька РІЗНИХ файлів + дія = кілька робіт, навіть якщо фраза
        # коротка. «додай у calc.py множення, а в notes.txt запиши» — це
        # дві окремі дії над двома файлами, і виконати їх треба обидві.
        # Раніше така фраза мала вагу 2 і не розбивалась: агент робив лише
        # першу половину й звітував «готово» (перевірено наживо).
        if len(self.paths) >= 2 and self.is_action:
            return True
        return len(self.intents) >= 3 and self.demands >= 2

    def label(self) -> str:
        return INTENT_LABELS.get(self.primary, "Розмова")


#: Пошук згадок файлів ВИНЕСЕНО в :mod:`path_scan` — і причина поважна.
#:
#: Тут стояла регулярка ``((?:[\w.\-]+[\\/])*[\w.\-]+\.(?:py|js|…))``. На
#: короткій фразі вона непомітна, але рушій regex пробує КОЖНУ стартову
#: позицію, і кожна невдала спроба сканує решту рядка — тобто квадратичний
#: час. Заміряно на вставленому тексті без шляху:
#:
#:     1 000 символів —    13 мс
#:     4 000 —            224 мс
#:     8 000 —            896 мс     ← інтерфейс уже «замислюється»
#:    20 000 —          5 136 мс
#:    50 000 —         32 453 мс     ← повне зависання на пів хвилини
#:
#: Тепер час лінійний (50 000 символів — 0.6 мс), бо шляхи шукаються одним
#: проходом за межами слів. Саму регулярку прибрано, щоб її не повернули
#: випадково: поведінку перевіряють ``path_scan.find_paths`` і тести.
_QUOTED = re.compile(r"[«\"'`]([^»\"'`]{2,})[»\"'`]")
_SENTENCE_SPLIT = re.compile(r"[.!?]+\s+|\n+")

