#: Стани етапу (ті самі слова, що в черзі задач — щоб не перекладати).
STAGE_PENDING = "очікує"
STAGE_RUNNING = "виконується"
STAGE_DONE = "готово"
STAGE_FAILED = "помилка"

#: Іконки станів.
STAGE_MARKS = {
    STAGE_PENDING: "○",
    STAGE_RUNNING: "◐",
    STAGE_DONE: "✓",
    STAGE_FAILED: "✗",
}

MAX_STAGES = 12


@dataclass
class Stage:
    """Один етап великої задачі."""

    text: str
    index: int = 0
    state: str = STAGE_PENDING
    tools: tuple[str, ...] = ()
    #: З якого наміру народився етап (для підпису й кольору).
    intent: str = TALK

    @property
    def mark(self) -> str:
        return STAGE_MARKS.get(self.state, "○")

    @property
    def running(self) -> bool:
        return self.state == STAGE_RUNNING

    @property
    def settled(self) -> bool:
        return self.state in (STAGE_DONE, STAGE_FAILED)

    def tools_text(self) -> str:
        """«читання файлу · правка фрагмента» — підпис під етапом."""
        labels = [TOOL_LABELS.get(tool, tool) for tool in self.tools]
        return " · ".join(labels)


def _clean_step(text: str) -> str:
    clean = " ".join((text or "").split())
    clean = re.sub(r"^[*\-•·]\s*", "", clean)
    clean = re.sub(r"^\d+[.)]\s*", "", clean)
    clean = clean.strip("\"'` ")
    return clean


def stage_from_text(text: str, index: int = 0, *,
                    fallback_intents: Iterable[str] = ()) -> Stage:
    """Створити етап із тексту кроку, додавши потрібні інструменти.

    ``fallback_intents`` — наміри всієї задачі. Якщо сам крок не назвав
    жодної дії («іконки закриття біля кожного чату»), етап успадковує
    намір задачі: інакше він лишався б без інструментів і модель на ньому
    поводилась би навмання.
    """
    clean = _clean_step(text)
    info = understand(clean)
    intents = [intent for intent in info.intents if intent != TALK]
    if not intents:
        intents = [intent for intent in fallback_intents if intent != TALK]
    return Stage(text=clean, index=index, tools=tools_for_intents(intents),
                 intent=intents[0] if intents else TALK)


