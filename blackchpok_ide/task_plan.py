def _word_present(low: str, word: str) -> bool:
    """Чи є слово в тексті ЯК ОКРЕМЕ слово (межі — не літери)."""
    pattern = r"(?<![A-Za-zА-Яа-яІіЇїЄєҐґ'’\-])" + re.escape(word) + \
              r"(?![A-Za-zА-Яа-яІіЇїЄєҐґ'’\-])"
    return re.search(pattern, low) is not None


def _needs_web(low: str) -> bool:
    """Чи потрібні дані з інтернету (а не з проєкту).

    Обережно: «яка ціна цієї функції» — це про код, тому перевіряємо
    наявність кодових слів і віддаємо їм перевагу.
    """
    hit = any(phrase in low for phrase in _WEB_PHRASES) or \
          any(_word_present(low, word) for word in _WEB_WORDS)
    if not hit:
        return False
    if any(marker in low for marker in _CODE_MARKERS):
        return False
    return True


def understand(text: str) -> Understanding:
    """Розібрати фразу користувача на наміри, об'єкти й масштаб."""
    clean = (text or "").strip()
    result = Understanding(text=clean)
    if not clean:
        return result
    low = clean.lower()

    found: dict[str, int] = {}
    for intent, stems in VERB_STEMS:
        hits = sum(1 for stem in stems if stem in low)
        if hits:
            found[intent] = hits

    # Об'єкти збираємо ЗАВЖДИ: навіть коли дії не розпізнано, названі
    # файли й символи в лапках потрібні (напр. для підказки «який файл?»).
    #
    # Пошук шляхів — ЛІНІЙНИЙ (:mod:`path_scan`), а не регулярка. Стара
    # регулярка на вставленому тексті без шляху працювала квадратично:
    # 8 000 символів — 0.9 с, 50 000 — 32 с. Для інтерфейсу це зависання.
    result.paths = path_scan.find_paths(clean)
    result.quoted = [m.group(1).strip() for m in _QUOTED.finditer(clean)]
    result.demands = _demands(low)
    result.sentences = max(1, len([s for s in _SENTENCE_SPLIT.split(clean) if s.strip()]))

    # ── Скарга на несправність — це завжди «полагодь» ─────────────────────
    # «нічого не відображається», «вилітає коли натискаю» — тут немає ні
    # дієслова-наказу, ні слова «помилка», але робота очевидна.
    if _has_complaint(low):
        found.setdefault(DEBUG, 0)
        found[DEBUG] += 2

    # ── Побутова мова: бажання + предмет ──────────────────────────────────
    # «мені потрібен калькулятор», «хочу гру», «треба щоб був сайт»,
    # «зроби шрифт більшим». Дієслова-наказу тут може не бути зовсім, зате
    # є бажання й конкретний предмет розробки.
    artifact = _has_artifact(low)
    desire = _has_desire(low)
    if desire and artifact and not found:
        # Визначаємо, ЩО саме просять: нове з нуля чи правку наявного.
        if _looks_creation(low):
            found[CREATE] = 1
        else:
            found[EDIT] = 1
    elif desire and artifact and CREATE not in found and EDIT not in found:
        # Дієслово знайдено (напр. UI через слово «меню»), але людина
        # просить СТВОРИТИ: «треба щоб був сайт з меню» — це створення
        # сайту, а не правка меню. Без цього правила намір зводився до
        # «інтерфейс», і агент шукав наявне меню замість нового сайту.
        if _looks_creation(low):
            found[CREATE] = 1
        elif _looks_edit(low):
            found[EDIT] = 1

    if not found:
        # ── Дані з інтернету ──────────────────────────────────────────────
        # «яка ціна SOL», «погода в Києві», «курс долара» — це НЕ балачка й
        # НЕ пошук по коду: відповідь живе в мережі. Раніше такі фрази
        # отримували підказку «search_text, find_files, list_dir», і модель
        # шукала ціну в репозиторії.
        if _needs_web(low):
            found[WEB] = 1
        # Питання про КОД — це доручення подивитись і відповісти.
        # «що в цьому файлі», «де використовується ця змінна»: людина
        # питає, але відповідь вимагає прочитати проєкт. Це не балачка.
        elif _is_code_question(low):
            if _has(low, "де ") or _has(low, "використов", "оголош", "виклик"):
                found[SEARCH] = 1
            else:
                found[READ] = 1
    elif _needs_web(low) and WEB not in found:
        # ── Мережа перекриває «побутовий» намір ───────────────────────────
        # «скільки коштує біткоїн» містить дієслово, яке розпізнається як
        # створення/правка («зроби»), і без цього правила запит про ціну
        # зводився до роботи з файлами. Якщо у фразі немає кодових слів,
        # але є ознака свіжих даних — це WEB.
        found = {WEB: 1}
    # ── Правка НАЯВНОГО файлу ─────────────────────────────────────────────
    # «у файлі calc.py додай функцію множення» — це правка, а не створення:
    # файл уже названо, і «додай» стосується його вмісту. Без цього правила
    # намір визначався як CREATE, і агент міг переписати файл цілком.
    if result.paths and CREATE in found and not _looks_new_file(low):
        found[EDIT] = found.get(EDIT, 0) + 1

    # ── Мережа перекриває «побутовий» намір ───────────────────────────────
    # «скільки коштує біткоїн» містить дієслово, яке розпізнається як
    # створення/правка, і без цього правила запит про ціну зводився до
    # роботи з файлами. Якщо у фразі немає кодових слів, але є ознака
    # свіжих даних — це WEB, і нічого іншого.
    if _needs_web(low) and not result.paths:
        found = {WEB: 1}

    if not found:
        result.intents = [TALK]
        return result

    result.intents = [intent for intent in _INTENT_PRIORITY if intent in found]
    # Наміри, яких немає в пріоритеті (напр. TALK), додаємо в кінець.
    result.intents += [intent for intent in found if intent not in result.intents]

    # «Зроби рефакторинг» — це REFACTOR, а не CREATE: «зроб» є в обох
    # наборах, і без цього правила створення перебивало рефакторинг.
    if REFACTOR in result.intents and result.intents[0] == CREATE:
        result.intents.remove(CREATE)
        if not result.intents:
            result.intents = [REFACTOR]

    # «Зроби шрифт більшим» — це ПРАВКА наявного, а не створення нового:
    # «зроб» є в обох наборах, і без цього правила проста зміна розміру
    # читалась як «створи файл». Ознака правки — порівняльний ступінь або
    # зміна властивості (колір, розмір, шрифт).
    if CREATE in result.intents and _looks_edit(low):
        result.intents = [EDIT if intent == CREATE else intent
                          for intent in result.intents]
        if EDIT not in result.intents:
            result.intents.append(EDIT)
        # Прибираємо дублікат, зберігаючи порядок пріоритету.
        result.intents = [intent for intent in _INTENT_PRIORITY
                          if intent in result.intents] + [
            intent for intent in result.intents
            if intent not in _INTENT_PRIORITY]

    # Вага: довжина, кількість вимог, кількість різних намірів, абзаци.
    weight = 0
    if len(clean) >= 120:
        weight += 1
    if len(clean) >= 260:
        weight += 1
    if result.demands >= 2:
        weight += 1
    if result.demands >= 4:
        weight += 1
    if len(result.intents) >= 2:
        weight += 1
    if len(result.intents) >= 3:
        weight += 1
    if clean.count("\n") >= 2:
        weight += 1
    if result.sentences >= 4:
        weight += 1
    result.weight = weight

    # «Як зробити чай?» — це запитання, а не доручення. Виконувати дію на
    # питальну фразу означало б відкривати файли замість відповіді.
    # Перевіряємо САМЕ питання, а не кількість вимог: слово «зробити»
    # входить і до словника вимог, тож за ним питальна фраза виглядала б
    # наказом. Виняток — великий опис: там питання буває лише вступом.
    #
    # Другий виняток — питальна фраза ПРО КОД («де використовується ця
    # змінна»): це доручення подивитись проєкт, і відповісти без читання
    # файлів неможливо.
    if _is_question(low) and weight < 4 and not _is_code_question(low):
        result.intents = [TALK]
        result.weight = 0

    return result


def _has(low: str, *needles: str) -> bool:
    """Чи є в тексті хоч одна з підстрок."""
    return any(needle in low for needle in needles)


