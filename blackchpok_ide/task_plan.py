def tools_hint(tools: Iterable[str]) -> str:
    """Рядок підказки для системного промпту: які інструменти доречні.

    Навіщо: модель бачить 20 інструментів одразу й часто бере не той.
    Коли на етапі явно названо 3–4 доречні, вона обирає серед них.
    """
    names = [tool for tool in tools if tool]
    if not names:
        return ""
    return ("Для цього етапу доречні інструменти: " + ", ".join(names) +
            ". Не викликай інших, якщо без них справді не обійтись.")


def append_hint(text: str) -> str:
    """Підказка «дописати, а не перезаписати», коли про це просять.

    Локальна модель на фразу «додай у notes.txt рядок» викликала
    ``write_file`` і затирала наявний вміст (перевірено наживо: файл із
    трьох рядків ставав одним). ``append_file`` існує, але модель про
    нього не згадує, поки їй прямо не сказати.
    """
    low = (text or "").lower()
    markers = ("додай", "додати", "добав", "допиши", "дописати", "доповни",
               "в кінці", "у кінець", "в кінець", "ще один рядок",
               "наприкінці", "після цього",
               # Етап може дістатися БЕЗ слова «додай»: після розбиття
               # фрази шматок читається як «notes.txt запиши що це
               # зроблено». Без цих маркерів підказка не спрацьовувала, і
               # модель перезаписувала файл.
               "запиши", "записати", "внеси", "внести", "занотуй")
    if not any(marker in low for marker in markers):
        return ""
    return ("Коли просять додати/дописати — використовуй append_file, "
            "а НЕ write_file: write_file затирає наявний вміст файлу.")


def stage_prompt(stage: Stage, *, total: int) -> str:
    """Текст задачі для одного етапу (іде в чергу або в чат)."""
    head = f"Етап {stage.index + 1} з {total}: {stage.text}"
    hint = tools_hint(stage.tools)
    return f"{head}\n\n{hint}" if hint else head


