#: Ділянки, які НЕ можна чіпати: код, шляхи, URL, інлайн-код.
#:
#: Без цього `get_state()` стало б `get_стан()`, а `C:\\tmp\\error.txt` —
#: `C:\\tmp\\помилка.txt`. Це не косметика, а псування даних.
CODE_SPAN = re.compile(
    r"```.*?```"                       # блок коду
    r"|`[^`\n]+`"                      # інлайн-код
    r"|https?://\S+"                   # URL
    r"|[A-Za-z]:\\[^\s\"'<>]+"         # Windows-шлях
    r"|[\w./-]+\.(?:py|js|ts|json|md|txt|ya?ml|toml|ini|cfg|html|css|sql"
    r"|go|rs|java|c|cpp|h|hpp|cs|sh|bat|ps1)\b"   # ім'я файлу
    r"|\b[A-Za-z_][A-Za-z0-9_]*\(\)",  # виклик функції
    re.DOTALL,
)

#: Рядки програмного коду — теж недоторканні.
#:
#: Заміряно: без цієї перевірки ``polish('if что == 1:')`` давав
#: ``'if що == 1:'``, а ``polish('print("что")')`` — ``'print("що")'``.
#: Тобто словник МІНЯВ ПРОГРАМУ замість тексту.
#:
#: ── ЧОМУ ПОТРІБНІ ДВІ ОЗНАКИ, А НЕ ОДНА ──────────────────────────────
#: Перша версія вважала кодом рядок із БУДЬ-ЯКОЮ ознакою, і це виявилось
#: надто агресивним: прозовий рядок «Перевір get_state() — там ошибка»
#: містить виклик, тож ЦІЛИЙ рядок захищався і російське слово лишалось
#: невиправленим. Заміряно тестом ``test_inline_code``.
#:
#: Тепер рядок вважається кодом, лише якщо має ОЗНАКУ СТРУКТУРИ
#: (ключове слово на початку, присвоєння, `;`/`{}` у кінці) АБО дві
#: незалежні ознаки. Просте згадування `func()` у реченні — не код.
_CODE_STRUCTURE = re.compile(
    r"^\s*(?:"
    r"(?:def|class|import|from|return|if|elif|else|for|while|try|except"
    r"|finally|with|lambda|assert|raise|del|global|nonlocal|yield"
    r"|async|await|match|case)\b"            # ключові слова Python
    r"|(?:const|let|var|function|public|private|protected|static"
    r"|package|namespace|using|struct|enum|interface|impl|fn|func)\b"
    r"|#!|@\w+"                              # шебанг, декоратор
    r")"
    r"|^\s*\w+\s*(?:=[^=]|\+=|-=|\*=|/=)"    # присвоєння на початку
    r"|[;{}]\s*$",                           # кінець інструкції
)


def _looks_like_code_line(line: str) -> bool:
    """Чи ЦЕЙ рядок — програмний код (а не проза зі згадкою функції)."""
    if _CODE_STRUCTURE.search(line):
        return True
    # Виклик із рядковим аргументом — це вже код: `print("что")`,
    # `log("помилка")`. Прозовий рядок так не виглядає: у ньому навколо
    # виклику є слова, а не лапки з дужками.
    if re.search(r"\w+\s*\(\s*[\"']", line):
        return True
    # Дві незалежні ознаки теж дають код: `x = foo()` у рядку.
    signals = 0
    if re.search(r"\w+\s*(?:==|!=|<=|>=|\+=|-=|\*=|/=)", line):
        signals += 1
    if re.search(r"\w+\([^)]*\)", line):
        signals += 1
    if re.search(r"^\s{2,}\S", line):        # відступ = тіло блоку
        signals += 1
    return signals >= 2

_WORD = r"(?<![\w\u0400-\u04FF]){}(?![\w\u0400-\u04FF])"


def _protected_spans(text: str) -> list[tuple[int, int]]:
    """Межі ділянок, які заміняти заборонено.

    Два рівні захисту:

    1. :data:`CODE_SPAN` — блоки коду, інлайн-код, шляхи, URL, імена файлів;
    2. :data:`_CODE_LINE` — ЦІЛІ рядки, схожі на програмний код.

    Другий рівень критичний: без нього ``polish('if что == 1:')`` давав
    ``'if що == 1:'``, тобто словник псував програму. Для агента, який пише
    код, це неприпустимо.
    """
    spans = [(match.start(), match.end()) for match in CODE_SPAN.finditer(text)]
    offset = 0
    for line in text.splitlines(keepends=True):
        if _looks_like_code_line(line):
            spans.append((offset, offset + len(line)))
        offset += len(line)
    return spans


def _inside(position: int, spans: Iterable[tuple[int, int]]) -> bool:
    return any(start <= position < end for start, end in spans)


def _apply(text: str, pair: tuple[str, str]) -> tuple[str, int]:
    """Замінити одну пару, не чіпаючи захищених ділянок."""
    source, target = pair
    if not source or source == target:
        return text, 0
    spans = _protected_spans(text)
    out: list[str] = []
    replaced = 0
    pattern = re.compile(_WORD.format(re.escape(source)), re.IGNORECASE)

    def keep_case(original: str) -> str:
        """Зберегти велику першу літеру: «Сейчас» → «Зараз»."""
        if original[:1].isupper():
            return target[:1].upper() + target[1:]
        return target

    position = 0
    for match in pattern.finditer(text):
        if _inside(match.start(), spans):
            continue
        out.append(text[position:match.start()])
        out.append(keep_case(match.group(0)))
        position = match.end()
        replaced += 1
    if not replaced:
        return text, 0
    out.append(text[position:])
    return "".join(out), replaced


def _replace_all(text: str, pairs: Iterable[tuple[str, str]]) -> tuple[str, int]:
    total = 0
    for pair in pairs:
        text, count = _apply(text, pair)
        total += count
    return text, total


def polish(text: str) -> str:
    """Прибрати русизми й суржик із ВІДПОВІДІ агента.

    Порядок важливий: спершу довші звороти («потому что», «приймати
    участь»), потім окремі слова. Інакше «потому что» стало б «потому що»
    (частково) і вже не збіглось би зі своєю парою.

    Код, шляхи й імена файлів лишаються НЕЗМІННИМИ.

    ``None`` і не-рядки повертаються ЯК Є: функція стоїть у гарячому шляху
    (``AgentRunner._emit``), і перетворення ``None`` у ``""`` змінило б
    поведінку викликача, який розрізняє «порожньо» й «не передано».
    """
    if text is None or not isinstance(text, str):
        return text
    body = text
    if not body.strip():
        return body
    # Довші фрази — першими.
    ordered = sorted(SURZHYK + CALQUES, key=lambda pair: -len(pair[0]))
    body, _ = _replace_all(body, ordered)
    body, _ = _replace_all(body, sorted(RUSSIAN_WORDS,
                                        key=lambda pair: -len(pair[0])))
    return body


def normalise(text: str) -> str:
    """Привести ВХІДНИЙ текст користувача до українського написання.

    Навіщо для входу: користувач цілком може написати «сделай файл» або
    «запусти тесты». Роутер інструментів шукає українські маркери, і без
    цього кроку намір не розпізнавався б.

    Це НЕ переклад: російське речення цілком лишиться російським, просто
    окремі слова стануть українськими — рівно настільки, щоб збігся пошук
    за маркерами.
    """
    body = str(text or "")
    if not body.strip():
        return body
    ordered = sorted(SURZHYK + CALQUES, key=lambda pair: -len(pair[0]))
    body, _ = _replace_all(body, ordered)
    body, _ = _replace_all(body, sorted(RUSSIAN_WORDS,
                                        key=lambda pair: -len(pair[0])))
    return body


def find_issues(text: str) -> list[str]:
    """Знайти русизми/суржик у тексті (для діагностики й тестів).

    Повертає знайдені слова у тому вигляді, як вони стоять у тексті. Код і
    шляхи не враховуються — так само, як у :func:`polish`.
    """
    body = str(text or "")
    if not body.strip():
        return []
    spans = _protected_spans(body)
    found: list[str] = []
    pairs = sorted({pair[0] for pair in
                    (*RUSSIAN_WORDS, *SURZHYK, *CALQUES)},
                   key=len, reverse=True)
    for source in pairs:
        if not source:
            continue
        pattern = re.compile(_WORD.format(re.escape(source)), re.IGNORECASE)
        for match in pattern.finditer(body):
            if _inside(match.start(), spans):
                continue
            found.append(match.group(0))
    return found
